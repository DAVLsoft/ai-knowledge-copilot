_SESSION_START = time.time()


def pytest_collection_modifyitems(config: pytest.Config, items: list[pytest.Item]) -> None:
    tests_root = config.rootpath / "tests"
    for item in items:
        kind = item.path.relative_to(tests_root).parts[0]
        if kind in {"unit", "integration"}:
            item.add_marker(getattr(pytest.mark, kind))


@pytest.hookimpl(trylast=True)
def pytest_terminal_summary(
    terminalreporter: pytest.TerminalReporter, config: pytest.Config
) -> None:
    """Finish the run with a link to the HTML coverage report.

    Only printed when the report was (re)generated by this run, so `--no-cov`
    never points to a stale report.
    """
    index = config.rootpath / "htmlcov" / "index.html"
    if index.exists() and index.stat().st_mtime >= _SESSION_START:
        terminalreporter.write_sep("=", "HTML coverage report")
        terminalreporter.write_line(index.as_uri())


